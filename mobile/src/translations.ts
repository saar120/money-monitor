export type MessageKey = keyof typeof english;
export { english, hebrew };
const i18n = new I18n({ en: english, he: hebrew });
i18n.enableFallback = true;

type TemplateFor<K extends MessageKey> = (typeof english)[K] extends string
  ? (typeof english)[K]
  : (typeof english)[K] extends { one: infer One extends string; other: infer Other extends string }
    ? `${One}${Other}`
    : never;
type Variables<S extends string> = S extends `${string}%{${infer Name}}${infer Rest}`
  ? Name | Variables<Rest>
  : never;
type TranslationArgs<K extends MessageKey> = [Variables<TemplateFor<K>>] extends [never]
  ? [options?: Record<string, never>]
  : [options: Record<Variables<TemplateFor<K>>, string | number>];

export function t<K extends MessageKey>(key: K, ...[options]: TranslationArgs<K>): string {
  i18n.locale = currentLanguage();
  return i18n.t(key, options);
}

export function ownerLabel(owner: string): string {
  if (owner === 'Shared') return t('shared');
  if (owner === 'Unassigned') return t('unassigned');
  if (owner === 'Unknown') return t('unknown');
  return owner;
}

export function categoryLabel(category: string): string {
  return category === 'Uncategorized' ? t('uncategorized') : category;
}

